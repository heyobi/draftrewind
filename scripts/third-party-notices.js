// Üçüncü taraf lisans bildirimlerini üretir: node scripts/third-party-notices.js
// Masaüstü (kök) ve mobil (mobile-expo) üretim bağımlılıklarının lisans metinlerini
// THIRD_PARTY_NOTICES.md dosyasına yazar. Bağımlılıklar değişince yeniden çalıştırın.
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
// Çift lisanslı paketlerde kullandığımız seçenek
const CHOSEN = { '(MIT OR GPL-3.0-or-later)': 'MIT', '(BSD-3-Clause OR GPL-2.0)': 'BSD-3-Clause', '(MIT OR Apache-2.0)': 'MIT', '(MIT OR CC0-1.0)': 'MIT' };

function collect(dir, selfName) {
    const json = execSync('npx --yes license-checker@25 --production --json', { cwd: dir, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });
    const data = JSON.parse(json);
    const out = [];
    for (const [id, info] of Object.entries(data)) {
        const name = id.slice(0, id.lastIndexOf('@'));
        if (name === selfName) continue;
        let text = '';
        if (info.licenseFile && /licen[cs]e|copying|notice/i.test(path.basename(info.licenseFile))) {
            try { text = fs.readFileSync(info.licenseFile, 'utf8').trim(); } catch (e) {}
        }
        const license = CHOSEN[info.licenses] ? `${CHOSEN[info.licenses]} (chosen from ${info.licenses})` : info.licenses;
        out.push({ id, license, repo: info.repository || '', publisher: info.publisher || '', text });
    }
    return out.sort((a, b) => a.id.localeCompare(b.id));
}

function section(title, list) {
    let md = `## ${title}\n\n| Package | License |\n|---|---|\n`;
    for (const p of list) md += `| ${p.repo ? `[${p.id}](${p.repo})` : p.id} | ${p.license} |\n`;
    md += '\n### License texts\n\n';
    const seen = new Map();
    for (const p of list) {
        if (!p.text) continue;
        const key = p.text.replace(/\s+/g, ' ');
        if (!seen.has(key)) seen.set(key, { text: p.text, ids: [] });
        seen.get(key).ids.push(p.id);
    }
    for (const { text, ids } of seen.values()) {
        md += `<details><summary>${ids.length > 3 ? `${ids.slice(0, 3).join(', ')} and ${ids.length - 3} more` : ids.join(', ')}</summary>\n\n\`\`\`\n${text.replace(/```/g, "'''")}\n\`\`\`\n\n${ids.length > 3 ? `Applies to: ${ids.join(', ')}\n\n` : ''}</details>\n\n`;
    }
    return md;
}

const desktop = collect(ROOT, 'draftrewind');
const mobile = fs.existsSync(path.join(ROOT, 'mobile-expo', 'node_modules')) ? collect(path.join(ROOT, 'mobile-expo'), 'mobile-expo') : [];
let md = `# Third-party notices\n\nDraftRewind is licensed under GPL-3.0-or-later. It includes the following third-party software, each under its own license. Generated by \`scripts/third-party-notices.js\`.\n\nDraftRewind does not include or run the Git program; Git compatibility is provided by isomorphic-git (MIT).\n\n`;
md += section('Desktop app (Electron)', desktop);
if (mobile.length) md += section('Mobile app (Expo / React Native)', mobile);
md += `## Optional AI components (downloaded on request, not bundled)

If the user enables local AI in Settings, DraftRewind downloads and verifies (SHA-256) llama.cpp build b11160 (MIT, https://github.com/ggml-org/llama.cpp) and the model Qwen3.5-2B (Apache-2.0, Qwen team; GGUF conversion by Unsloth, https://huggingface.co/unsloth/Qwen3.5-2B-GGUF). The iOS app uses Apple's on-device Foundation Models via the operating system.

`;
    md += `## Web libraries bundled with the mobile document viewer\n\nThe mobile viewer bundles these files (loaded offline, no network requests): jszip 3.10.1 (MIT), docx-preview 0.4.1 (Apache-2.0), xlsx / SheetJS CE 0.18.5 (Apache-2.0), diff (jsdiff) 5.2.0 (BSD-3-Clause).\n`;
fs.writeFileSync(path.join(ROOT, 'THIRD_PARTY_NOTICES.md'), md);
console.log(`THIRD_PARTY_NOTICES.md: ${desktop.length} masaüstü, ${mobile.length} mobil paket`);
