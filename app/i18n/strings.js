    const LANGS = Object.keys(STRINGS);
    let current = 'tr';

    // 'tr-TR', 'tr' → 'tr'; anything else → 'en'
    function resolve(pref, systemLocales) {
        if (pref && pref !== 'auto' && STRINGS[pref]) return pref;
        const list = Array.isArray(systemLocales) ? systemLocales : [systemLocales];
        for (const l of list) {
            if (!l) continue;
            return /^tr\b|^tr[-_]/i.test(String(l)) ? 'tr' : 'en';
        }
        return 'en';
    }

    function pick(entry, vars) {
        if (entry && typeof entry === 'object' && !Array.isArray(entry)) {
            const c = vars && (typeof vars.count === 'number' ? vars.count : typeof vars.n === 'number' ? vars.n : null);
            return Math.abs(c) === 1 ? entry.one : entry.other;
        }
        return entry;
    }

    function t(lang, key, vars) {
        const dict = STRINGS[lang] || STRINGS.tr;
        let v = key in dict ? dict[key] : key in STRINGS.tr ? STRINGS.tr[key] : key;
        v = pick(v, vars);
        if (Array.isArray(v)) return v;
        if (!vars) return v;
        return String(v).replace(/\{(\w+)\}/g, (m, k) => (k in vars && vars[k] != null ? String(vars[k]) : m));
    }

    const api = {
        STRINGS,
        LANGS,
        t,
        resolve,
        setLanguage(l) { current = STRINGS[l] ? l : 'tr'; },
        getLanguage() { return current; },
        locale(lang) { return t(lang || current, 'locale'); },
        // current-language shortcut
        text(key, vars) { return t(current, key, vars); }
    };

    if (typeof module !== 'undefined' && module.exports) module.exports = api;
    else root.I18N = api;
